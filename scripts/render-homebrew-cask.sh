#!/usr/bin/env bash
# Render the Homebrew cask for infomosquitos/homebrew-tap from a release's
# SHA256SUMS. Writes Ruby to stdout.
# Usage: render-homebrew-cask.sh <version> <SHA256SUMS>
#   version: tag or semver (e.g. v0.7.0 or 0.7.0); the cask gets it without "v".
set -euo pipefail

VERSION="${1:?usage: render-homebrew-cask.sh <version> <SHA256SUMS>}"
SUMS="${2:?usage: render-homebrew-cask.sh <version> <SHA256SUMS>}"
VERSION="${VERSION#v}"

sha_for() {
  local sha
  sha="$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$SUMS")"
  if [[ ! "$sha" =~ ^[0-9a-f]{64}$ ]]; then
    echo "render-homebrew-cask: no sha256 for $1 in $SUMS" >&2
    exit 1
  fi
  echo "$sha"
}

SHA_ARM="$(sha_for spacemosquito-darwin-arm64.tar.gz)"
SHA_INTEL="$(sha_for spacemosquito-darwin-amd64.tar.gz)"

cat <<EOF
# Generated by scripts/render-homebrew-cask.sh in infomosquitos/spacemosquito.
# Do not edit by hand: the release workflow overwrites this file.
cask "spacemosquito" do
  arch arm: "arm64", intel: "amd64"

  version "${VERSION}"
  sha256 arm:   "${SHA_ARM}",
         intel: "${SHA_INTEL}"

  url "https://github.com/infomosquitos/spacemosquito/releases/download/v#{version}/spacemosquito-darwin-#{arch}.tar.gz"
  name "SpaceMosquito"
  desc "Confluence space scraper, indexer and local MCP search server"
  homepage "https://github.com/infomosquitos/spacemosquito"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on :macos

  # The archive also holds spacemosquito-embedder and lib/ (llama.cpp),
  # found next to the resolved binary.
  binary "spacemosquito"

  # Release binaries and libraries are not notarized; drop the quarantine
  # flag so Gatekeeper does not block the first run.
  postflight_steps do
    run "/usr/bin/xattr",
        args:           ["-dr", "com.apple.quarantine", "{{staged_path}}"],
        writable_paths: ["{{staged_path}}"],
        must_succeed:   false
    # Semantic search model (bge-m3, 635 MB; ADR-019): downloaded once from
    # this project's release and sha256-checked by spacemosquito itself;
    # upgrades find it in place. Without it search is keyword-only.
    unless_path_exists "{{HOMEBREW_PREFIX}}/share/spacemosquito/models/bge-m3-q8_0.gguf" do
      run "{{staged_path}}/spacemosquito",
          args:           ["model", "install", "--dir", "{{HOMEBREW_PREFIX}}/share/spacemosquito/models"],
          writable_paths: ["{{HOMEBREW_PREFIX}}/share/spacemosquito"],
          network_access: true,
          print_stdout:   true,
          must_succeed:   false
    end
  end

  zap trash: [
    "~/.spacemosquito",
    "#{HOMEBREW_PREFIX}/share/spacemosquito",
  ]

  caveats <<~EOS
    Next steps:

    1. Create config, database and encryption key in ~/.spacemosquito:
         spacemosquito init
       (add --download-browser to pre-fetch Chromium, ~150 MB, for fallback crawls)

    2. Start the server (keep it running; it listens on http://localhost:56403):
         spacemosquito serve

    3. Install the browser extension (Homebrew cannot do this for you).
       Download it from https://github.com/infomosquitos/spacemosquito/releases/tag/v#{version}
         Firefox: spacemosquito-firefox-v#{version}.xpi
                  about:addons -> gear icon -> Install Add-on From File...
         Chrome:  spacemosquito-chrome-v#{version}.zip, unzip it into a folder you keep:
                    mkdir -p ~/Applications/SpaceMosquito-Chrome
                    unzip -o ~/Downloads/spacemosquito-chrome-v#{version}.zip -d ~/Applications/SpaceMosquito-Chrome
                  chrome://extensions -> Developer mode -> Load unpacked ->
                  select that folder (not the .zip)
       Details: https://github.com/infomosquitos/spacemosquito/blob/main/docs/INSTALL.md#browser-extension

    4. Log in to Confluence, open the SpaceMosquito extension popup and click
       "Session" to send your login to the local server.

    5. Crawl a space from the popup's Spaces tab, or from the terminal:
         spacemosquito crawl "https://your-domain.atlassian.net/wiki/spaces/SPACEKEY"
       Then click 📖 next to the space to browse the saved pages
       (served by spacemosquito serve at http://localhost:56403/browse/;
       for a copy without the server: spacemosquito export-html ~/SpaceMosquito-export).

    6. Search understands questions, not only keywords: serve embeds your
       pages in the background (about 10 minutes per ~1,000 pages) with the
       bge-m3 model downloaded at install (635 MB, once). If that download
       failed, run:
         spacemosquito model install --dir "#{HOMEBREW_PREFIX}/share/spacemosquito/models"
       Set embedder.provider: none in ~/.spacemosquito/config.yaml for
       keyword search only.

    7. Optional: connect AI agents via MCP at http://127.0.0.1:56403/mcp
       https://github.com/infomosquitos/spacemosquito/blob/main/docs/guides/configure-mcp.md

    \`brew uninstall --zap spacemosquito\` also deletes ~/.spacemosquito
    (catalog, config and encryption key) and the model.
  EOS
end
EOF
