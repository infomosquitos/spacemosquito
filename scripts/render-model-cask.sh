#!/usr/bin/env bash
# Render the Homebrew cask of the semantic search model (ADR-019) for
# infomosquitos/homebrew-tap. The spacemosquito cask depends on it, so the
# 635 MB model is downloaded once, not with every app upgrade. The file is
# the llama.cpp project's GGUF conversion of BAAI/bge-m3 (MIT), pinned to a
# Hugging Face revision and verified by sha256; spacemosquito finds it in
# $(brew --prefix)/share/spacemosquito/models. Writes Ruby to stdout.
#
# Changing the model: update REVISION, SHA256 and FILE (and embed.ModelFile),
# and bump VERSION so existing installs upgrade.
set -euo pipefail

VERSION="1"
REVISION="9eba04c5d75ba5a1595e45de734d36bef4e5cb98"
FILE="bge-m3-q8_0.gguf"
SHA256="aa473d51f451a22f0fcf39ba3330c14bed38a385712b1113440f69df4047a173"

cat <<RUBY
# Generated by scripts/render-model-cask.sh in infomosquitos/spacemosquito.
# Do not edit by hand: the release workflow overwrites this file.
cask "spacemosquito-bge-m3-embeddings-model" do
  version "${VERSION}"
  sha256 "${SHA256}"

  url "https://huggingface.co/ggml-org/bge-m3-Q8_0-GGUF/resolve/${REVISION}/${FILE}"
  name "bge-m3 embedding model for SpaceMosquito"
  desc "Multilingual text embedding model (BAAI/bge-m3, GGUF Q8_0) for semantic search"
  homepage "https://huggingface.co/BAAI/bge-m3"

  artifact "${FILE}", target: "#{HOMEBREW_PREFIX}/share/spacemosquito/models/${FILE}"
end
RUBY
